def ensure_tags(db):
    """把 100 个标签灌进 tags 表（幂等，只补不删）。"""
    import time
    now = time.time()
    added = 0
    for name, _desc, _rx in TAG_LIBRARY:
        row = db.execute("SELECT id FROM tags WHERE name=?", (name,)).fetchone()
        if not row:
            db.execute("INSERT INTO tags (name, use_count, created_at) VALUES (?,0,?)",
                       (name, now))
            added += 1
    db.commit()
    return added
